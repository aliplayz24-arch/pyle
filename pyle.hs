module Main where

import System.Environment (getArgs)
import System.Process (readProcessWithExitCode, callProcess)
import System.Exit (exitWith, ExitCode(..), exitFailure)
import System.IO
import Data.Char (isSpace)
import Data.List (isPrefixOf, intercalate, nub)
import Text.Printf (printf)

-- -------------------------------------------------------------
-- 1. PYTHON METADATA & IMPORT ANALYZER
-- -------------------------------------------------------------

data PyImport
  = ModImport String
  | FromImport String String
  deriving (Show, Eq)

extractImports :: String -> [PyImport]
extractImports src = concatMap parseLine (lines src)
  where
    parseLine l =
      let ws = words (takeWhile (/= '#') l)
      in case ws of
        ("import" : mods) ->
          map (ModImport . filter (/= ',')) (filter (/= "as") mods)
        ("from" : modName : "import" : targets) ->
          map (FromImport modName . filter (/= ',')) (filter (/= "as") targets)
        _ -> []

-- -------------------------------------------------------------
-- 2. AOT BYTECODE COMPILER
-- -------------------------------------------------------------

compileToBytecode :: String -> FilePath -> IO (Either String [Integer])
compileToBytecode src sourcePath = do
  let pyScript = unlines
        [ "import marshal, sys"
        , "src = sys.stdin.read()"
        , "try:"
        , "    code = compile(src, " ++ show sourcePath ++ ", 'exec')"
        , "    dump = marshal.dumps(code)"
        , "    sys.stdout.write(','.join(str(b) for b in dump))"
        , "except Exception as e:"
        , "    sys.stderr.write(str(e))"
        , "    sys.exit(1)"
        ]
  (exitCode, stdout, stderr) <- readProcessWithExitCode "python3" ["-c", pyScript] src
  case exitCode of
    ExitSuccess -> do
      let cleaned = filter (not . isSpace) stdout
      if null cleaned
        then return (Right [])
        else return (Right (read ("[" ++ cleaned ++ "]") :: [Integer]))
    ExitFailure _ -> return (Left stderr)

-- -------------------------------------------------------------
-- 3. HARDENED NATIVE C RUNTIME GENERATOR
-- -------------------------------------------------------------

generateNativeC :: [Integer] -> FilePath -> FilePath -> String
generateNativeC bytecodeBytes sourcePath sysPythonPath = unlines
  [ "/* Generated by Haskell PyCompiler (Hardened Native AOT) */"
  , "#define PY_SSIZE_T_CLEAN"
  , "#include <Python.h>"
  , "#include <marshal.h>"
  , "#include <wchar.h>"
  , ""
  , "static const unsigned char aot_bytecode[] = {"
  , formatHexDump bytecodeBytes
  , "};"
  , "static const size_t aot_bytecode_len = " ++ show (length bytecodeBytes) ++ ";"
  , ""
  , "int main(int argc, char *argv[]) {"
  , "    PyStatus status;"
  , "    PyConfig config;"
  , "    PyConfig_InitPythonConfig(&config);"
  , ""
  , "    /* 1. Prevent Python from intercepting app arguments (-v, -h, etc.) */"
  , "    config.parse_argv = 0;"
  , ""
  , "    /* 2. Lock program_name to system python so it finds standard libraries (encodings, etc.) */"
  , "    status = PyConfig_SetBytesString(&config, &config.program_name, " ++ show sysPythonPath ++ ");"
  , "    if (PyStatus_Exception(status)) { PyConfig_Clear(&config); return 1; }"
  , ""
  , "    /* 3. Forward exact command-line arguments to sys.argv */"
  , "    status = PyConfig_SetBytesArgv(&config, argc, argv);"
  , "    if (PyStatus_Exception(status)) { PyConfig_Clear(&config); return 1; }"
  , ""
  , "    /* 4. Boot the CPython Runtime Engine */"
  , "    status = Py_InitializeFromConfig(&config);"
  , "    PyConfig_Clear(&config);"
  , "    if (PyStatus_Exception(status)) { return 1; }"
  , ""
  , "    /* 5. Inject current directory into sys.path so local imports work */"
  , "    PyRun_SimpleString(\"import sys, os\\n\""
  , "                       \"if '' not in sys.path:\\n\""
  , "                       \"    sys.path.insert(0, os.path.abspath('.'))\\n\");"
  , ""
  , "    /* 6. Populate __main__ dictionary with __file__ and __name__ */"
  , "    PyObject *main_mod = PyImport_AddModule(\"__main__\");"
  , "    PyObject *global_dict = PyModule_GetDict(main_mod);"
  , "    PyDict_SetItemString(global_dict, \"__file__\", PyUnicode_FromString(" ++ show sourcePath ++ "));"
  , "    PyDict_SetItemString(global_dict, \"__name__\", PyUnicode_FromString(\"__main__\"));"
  , ""
  , "    /* 7. Unmarshal and execute the compiled AOT bytecode */"
  , "    PyObject *code_obj = PyMarshal_ReadObjectFromString((const char *)aot_bytecode, aot_bytecode_len);"
  , "    if (!code_obj) {"
  , "        PyErr_Print();"
  , "        Py_Finalize();"
  , "        return 1;"
  , "    }"
  , ""
  , "    PyObject *result = PyEval_EvalCode(code_obj, global_dict, global_dict);"
  , "    int exit_code = 0;"
  , ""
  , "    if (!result) {"
  , "        if (PyErr_ExceptionMatches(PyExc_SystemExit)) {"
  , "            PyObject *exc, *val, *tb;"
  , "            PyErr_Fetch(&exc, &val, &tb);"
  , "            if (val && PyLong_Check(val)) {"
  , "                exit_code = (int)PyLong_AsLong(val);"
  , "            }"
  , "        } else {"
  , "            PyErr_Print();"
  , "            exit_code = 1;"
  , "        }"
  , "    } else {"
  , "        Py_DECREF(result);"
  , "    }"
  , ""
  , "    Py_DECREF(code_obj);"
  , "    Py_Finalize();"
  , "    return exit_code;"
  , "}"
  ]
  where
    formatHexDump bytes =
      let chunks = splitInto 16 bytes
          formatLine chunk = "    " ++ intercalate ", " (map (printf "0x%02x") chunk) ++ ","
      in unlines (map formatLine chunks)

    splitInto _ [] = []
    splitInto n list = take n list : splitInto n (drop n list)

-- -------------------------------------------------------------
-- 4. ENVIRONMENT & LINKER FLAG DETECTOR
-- -------------------------------------------------------------

getSystemPythonPath :: IO String
getSystemPythonPath = do
  (code, out, _) <- readProcessWithExitCode "python3" ["-c", "import sys; print(sys.executable)"] ""
  return $ if code == ExitSuccess then filter (not . isSpace) out else "/usr/bin/python3"

getLinkerFlags :: IO (Either String (String, String))
getLinkerFlags = do
  (codeC, cflags, errC) <- readProcessWithExitCode "python3-config" ["--cflags"] ""
  -- Try --embed first (Python 3.8+), fallback to standard --ldflags
  (codeL1, ldflags1, _) <- readProcessWithExitCode "python3-config" ["--ldflags", "--embed"] ""
  (codeL, ldflags, errL) <- if codeL1 == ExitSuccess
                              then return (codeL1, ldflags1, "")
                              else readProcessWithExitCode "python3-config" ["--ldflags"] ""

  if codeC /= ExitSuccess || codeL /= ExitSuccess
    then return (Left $ "python3-config failed: " ++ errC ++ " " ++ errL)
    else return (Right (unwords (words cflags), unwords (words ldflags)))

-- -------------------------------------------------------------
-- 5. COMPILER CLI & DRIVER
-- -------------------------------------------------------------

data Options = Options
  { optInput   :: FilePath
  , optOutput  :: FilePath
  , optKeepC   :: Bool
  , optVerbose :: Bool
  } deriving Show

parseArgs' :: [String] -> Options -> Either String Options
parseArgs' [] opts
  | null (optInput opts) = Left "No input file provided."
  | otherwise            = Right opts
parseArgs' ("-o" : out : rest) opts = parseArgs' rest (opts { optOutput = out })
parseArgs' ("--keep-c" : rest) opts = parseArgs' rest (opts { optKeepC = True })
parseArgs' ("-v" : rest) opts       = parseArgs' rest (opts { optVerbose = True })
parseArgs' (fn : rest) opts
  | null (optInput opts) = parseArgs' rest (opts { optInput = fn })
  | otherwise            = Left $ "Unexpected argument: " ++ fn

main :: IO ()
main = do
  args <- getArgs
  case parseArgs' args (Options "" "a.out" False False) of
    Left err -> do
      putStrLn $ "Error: " ++ err
      putStrLn "Usage: runghc PyCompiler.hs <source.py> [-o <binary>] [--keep-c] [-v]"
      exitFailure

    Right opts -> do
      let srcFile = optInput opts
      let outFile = optOutput opts
      let cFile = outFile ++ ".c"

      putStrLn "=========================================================="
      putStrLn "    HASKELL NATIVE PYTHON AOT COMPILER (PyCompile)        "
      putStrLn "=========================================================="
      putStrLn $ "[1/4] Reading source: " ++ srcFile
      srcContent <- readFile srcFile

      -- 1. Scan Imports
      let foundImports = extractImports srcContent
      putStrLn $ "[2/4] Scanned " ++ show (length foundImports) ++ " top-level module import(s):"
      mapM_ (\i -> putStrLn $ "      -> " ++ show i) (nub foundImports)

      -- 2. Compile Bytecode
      putStrLn "[3/4] Compiling AST into Bytecode..."
      bytecodeRes <- compileToBytecode srcContent srcFile
      case bytecodeRes of
        Left err -> do
          putStrLn "\n--- [PYTHON COMPILATION ERROR] ---"
          putStrLn err
          exitFailure
        Right bytes -> do
          putStrLn $ "      Compiled Bytecode Size: " ++ show (length bytes) ++ " bytes."

          -- 3. Emit C Glue
          sysPy <- getSystemPythonPath
          let cCode = generateNativeC bytes srcFile sysPy
          writeFile cFile cCode

          -- 4. Build Native Binary
          putStrLn $ "[4/4] Invoking GCC / Host Linker: " ++ outFile
          flagsRes <- getLinkerFlags
          case flagsRes of
            Left err -> do
              putStrLn err
              exitFailure
            Right (cflags, ldflags) -> do
              let gccCmd = "gcc -O2 " ++ cFile ++ " " ++ cflags ++ " " ++ ldflags ++ " -o " ++ outFile
              if optVerbose opts then putStrLn $ "Exec: " ++ gccCmd else return ()

              (gccExit, _, gccErr) <- readProcessWithExitCode "bash" ["-c", gccCmd] ""
              case gccExit of
                ExitFailure _ -> do
                  putStrLn "\n--- [C LINKER ERROR] ---"
                  putStrLn gccErr
                  exitFailure
                ExitSuccess -> do
                  if not (optKeepC opts) then callProcess "rm" ["-f", cFile] else return ()
                  putStrLn "=========================================================="
                  putStrLn $ "SUCCESS: Native Executable Compiled -> ./" ++ outFile
                  putStrLn "=========================================================="
